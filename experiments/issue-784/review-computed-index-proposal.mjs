// Independently replay the entire proposal before installing generated copies.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,copyFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {gunzipSync,gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {transportConcreteSyntaxSource,transportConcreteSyntaxMeta,serializeConcreteSyntaxMeta} from '../../tools/translation/concrete-syntax-meta.mjs';
import {ownershipCompiler} from '../../tools/translation/js-to-rust/vendor/module-syntax.mjs';
const root=fileURLToPath(new URL('../../',import.meta.url)),base=resolve(root,'ci-logs/issue-784-restart-2');
const input='/tmp/router-issue-784-computed-index-proposal/complete-source-proposal-and-inverses.json.gz';
const raw=gunzipSync(readFileSync(input),{maxOutputLength:32*1024*1024}),proposal=JSON.parse(raw);
const expected=['matrix-bulk.mjs','retained-matrix-bulk.mjs','owned-definitions-matrix-bulk.mjs','retained-owned-definitions-matrix-bulk.mjs'].map(name=>'tools/translation/isolated-'+name).concat('scripts/translate-router.mjs');
assert.equal(proposal.schema,'complete-isolated-matrix-source-proposal-v1');assert.deepEqual(proposal.files.map(row=>row.path),expected);
assert.equal(proposal.fullOriginalAPIsUnchanged,true);const hash=value=>createHash('sha256').update(value).digest('hex');
const ts=ownershipCompiler(),started=performance.now(),reviews=[];
function check(source){
 const serialized=serializeConcreteSyntaxMeta(transportConcreteSyntaxSource(source,{language:'JavaScript'}).document);
 assert.equal(transportConcreteSyntaxMeta(serialized).source,source);
 const parsed=ts.createSourceFile('whole-index-custody.mjs',source,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
 assert.equal(parsed.parseDiagnostics.length,0);return serialized;
}
for(const row of proposal.files){
 assert.equal(row.sourceSha256,hash(row.source));assert.equal(row.sha256,hash(row.text));assert.equal(row.inverse,row.source);
 assert.equal(transportConcreteSyntaxMeta(row.beforeMeta).source,row.source);assert.equal(transportConcreteSyntaxMeta(row.afterMeta).source,row.text);
 const original=row.path.startsWith('tools/')?row.path.replace('/isolated-','/'):row.path;
 const before=readFileSync(resolve(root,row.path),'utf8'),physical=readFileSync(resolve(root,original),'utf8');
 assert.equal(execFileSync('git',['show','b63dd5a337c4e17f9df51f9ce866cb73fdea7662:'+original],{cwd:root,encoding:'utf8'}),physical);
 assert.equal(row.currentSource??row.source,physical);
 let source=row.source;const phases=[];
 for(const phase of ['language','repository']){
  const beforeSource=source;
  for(const rule of row.rules.filter(rule=>rule.phase===phase||!rule.phase&&phase==='language')){
   assert.equal(source.split(rule.before).length,2);source=source.replace(rule.before,()=>rule.after);
  }
  phases.push({phase,beforeMeta:check(beforeSource),afterMeta:check(source)});
 }
 const header=row.path.startsWith('tools/')?'// Generated by prepare-isolated-matrix.mjs from the complete original matrix.\n// Sequential stock-process DATA custody; every original compiler check remains.\n':'';
 assert.equal(header+source,row.text);
 for(const rule of [...row.rules].reverse()){assert.equal(source.split(rule.after).length,2);source=source.replace(rule.after,()=>rule.before);}
 assert.equal(source,row.source);assert.equal(row.semanticAuthority,false);
 if(header){assert.equal(row.text.split('isolation.retainComputedIndices(').length,2);assert.ok(row.text.includes('{check,deferDraft:true}'));}
 reviews.push({path:row.path,original,originalSource:physical,installedPreimage:before,completeInverse:source,phases});
 assert.ok(performance.now()-started<60000,'Complete source replay exceeded experiment cap');
}
copyFileSync(input,resolve(base,'computed-index-complete-proposal.json.gz'));
for(const row of proposal.files){writeFileSync(resolve(root,row.path),row.text);assert.equal(readFileSync(resolve(root,row.path),'utf8'),row.text);}
const receipt={schema:'whole-computed-index-source-review-v1',proposalSha256:hash(raw),reviews,semanticAuthority:false,runtimeParity:false,rustExecuted:false};
const encoded=Buffer.from(JSON.stringify(receipt)),target=resolve(base,'computed-index-source-review.json.gz');
writeFileSync(target,gzipSync(encoded),{flag:'wx'});assert.deepEqual(gunzipSync(readFileSync(target)),encoded);
console.log(JSON.stringify({completeFiles:reviews.length,phases:['language','repository'],installed:true,fullGatePassed:false}));
