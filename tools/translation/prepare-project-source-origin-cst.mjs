const root=fileURLToPath(new URL('../../',import.meta.url));
const base='tools/translation/',hash=value=>createHash('sha256').update(value).digest('hex');
const fail=message=>{throw TypeError('Project source-origin CST preparation: '+message);};
const sourcePath=base+'forward-concrete-syntax.mjs';
const targetPath=base+'forward-source-origin-concrete-syntax.mjs';
const projectPath=base+'project.mjs';
const oldImport="import {createRustConcreteSyntaxStage,createRustConcreteSyntaxStages} from './forward-concrete-syntax.mjs';";
const newImport="import {createRustConcreteSyntaxStage} from './forward-concrete-syntax.mjs';\nimport {createRustConcreteSyntaxSourceStages} from './forward-source-origin-concrete-syntax.mjs';";
const oldCall='createRustConcreteSyntaxStages(captured.map(row=>row.source))';
const newCall='createRustConcreteSyntaxSourceStages(captured.map(row=>row.source))';
